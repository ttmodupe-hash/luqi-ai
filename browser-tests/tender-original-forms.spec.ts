import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {unzipSync,strFromU8} from 'fflate';
const fixture='tests/fixtures/tenders/treasury-revised-sbd1.docx';
test('the actual Treasury original is filled locally, exported with approval history and cleared after edits',async({page},testInfo)=>{
 await page.setViewportSize({width:320,height:740});
 const outbound:string[]=[];
 page.on('request',req=>{if(req.method()!=='GET'||/api\.openai|generativelanguage|\/luqi-core/.test(req.url()))outbound.push(req.method()+' '+req.url())});
 await page.goto('/#/tenders');
 const panel=page.getByRole('region',{name:'Original government form assistance'});
 await expect(panel.getByLabel('Import original tender document')).toBeDisabled();
 await panel.getByRole('checkbox',{name:/I authorise local processing/}).check();
 await panel.getByLabel('Import original tender document').setInputFiles(fixture);
 await expect(panel.getByText(/Exact Treasury original verified/)).toBeVisible();
 await panel.getByLabel('SBD 1 Name of bidder').fill('Synthetic bidder & partners');
 await panel.getByLabel('SBD 1 Email address').fill('synthetic@example.test');
 await panel.getByLabel('Tender reference',{exact:true}).fill('SYNTHETIC-LOCAL-001');
 await panel.getByLabel('Procuring authority',{exact:true}).fill('Synthetic authority - no real bid');
 await panel.getByLabel('Applicant or authorised representative',{exact:true}).fill('Synthetic applicant');
 await panel.getByLabel('Closing time with timezone').fill('2090-11-30T11:00+02:00');
 await panel.getByLabel('Exact official submission address').fill('Synthetic bid box');
 await panel.getByLabel('Applicant-entered offer ZAR').fill('1000.00');
 await panel.getByLabel('Original form submission method').selectOption('physical');
 await panel.getByRole('button',{name:'Prepare exact original for review'}).click();
 const review=panel.getByRole('region',{name:'Original form applicant review'});
 await expect(review).toBeVisible();
 const checks=review.getByRole('checkbox');await expect(checks).toHaveCount(7);
 await expect(checks.nth(6)).toBeDisabled();
 for(let i=0;i<7;i++)await checks.nth(i).check();
 await expect(review.getByRole('button',{name:'Export filled original and review record'})).toBeEnabled();
 const downloadPromise=page.waitForEvent('download');
 await review.getByRole('button',{name:'Export filled original and review record'}).click();
 const download=await downloadPromise;expect(download.suggestedFilename()).toBe('luqi-sbd1-partial-review-pack.zip');
 const path=await download.path();expect(path).toBeTruthy();
 const files=unzipSync(readFileSync(path!));
 expect(files['original.docx']).toEqual(new Uint8Array(readFileSync(fixture)));
 const filled=unzipSync(files['filled-sbd1-partial.docx']);
 expect(strFromU8(filled['word/document.xml'])).toContain('Synthetic bidder &amp; partners');
 const record=JSON.parse(strFromU8(files['luqi-review-record.json']));
 expect(record.approval.gates).toHaveLength(7);expect(record.submissionConnected).toBe(false);expect(record.legallySigned).toBe(false);
 expect(record.context.priceZar).toBe('1000.00');expect(record.history.events.some((e:{action:string})=>e.action==='export')).toBe(true);
 expect(outbound).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await panel.screenshot({path:testInfo.outputPath('tender-original-form.png')});
 await panel.getByLabel('Applicant-entered offer ZAR').fill('2000.00');
 await expect(review).toHaveCount(0);
 await panel.getByRole('button',{name:'Clear private document work'}).click();
 await expect(panel.getByLabel('SBD 1 Name of bidder')).toHaveCount(0);
});
test('pinned original loading is explicit and a changed lookalike cannot use the fill workflow',async({page})=>{
 await page.goto('/#/tenders');
 const panel=page.getByRole('region',{name:'Original government form assistance'});
 await panel.getByRole('checkbox',{name:/I authorise local processing/}).check();
 await panel.getByRole('button',{name:'Use verified Treasury SBD 1'}).click();
 await expect(panel.getByText(/Treasury original verified/)).toBeVisible();
 await panel.getByLabel('Import original tender document').setInputFiles({name:'lookalike.docx',mimeType:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',buffer:Buffer.from('not a document')});
 await expect(panel.getByLabel('SBD 1 Name of bidder')).toHaveCount(0);
 await expect(panel.getByRole('button',{name:'Prepare exact original for review'})).toHaveCount(0);
});
