import { test, expect } from '@playwright/test';
for (const width of [390,1280]) {
  test('in-page Luqi People and P2P stay inside one chat shell at '+width+'px', async ({page}, info) => {
    let logins=0,paid=0,reads=0;
    page.on('request',r=>{if(r.method()==='POST'&&r.url().includes('/luqi-core'))paid++});
    await page.route('**/v1/readiness',r=>r.fulfill({json:{checks:{persistence:'connected',ai_pilot:'configured_not_verified'}}}));
    await page.route('**/api/v1/auth/login',r=>{logins++;return r.fulfill({json:{token:'synthetic-dock-token',user:{email:'dock@example.invalid',name:'Naledi'}}})});
    await page.route('**/api/v1/p2p/status',r=>r.fulfill({json:{enabled:true,userId:7,eligibility:'verified_adult',circles:[],blockedPeers:[]}}));
    await page.route('**/api/v1/p2p/contacts',r=>{reads++;return r.fulfill({json:{contacts:[{circleId:'552987fe-97a1-41df-a090-a5df75eb8de8',userId:8,name:'Approved study partner',accountActive:true,presence:'not_shared'}]}})});
    await page.setViewportSize({width,height:900});
    await page.goto('/#/login');
    await page.getByLabel('Email',{exact:true}).fill('dock@example.invalid');
    await page.getByLabel('Password',{exact:true}).fill('Synthetic-Private-Password-2026!');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page.getByLabel('Your question')).toBeVisible();
    const rail=page.getByRole('complementary',{name:'Luqi contacts'});
    const contacts=page.getByRole('region',{name:'Your contacts'});
    await expect(rail.getByRole('heading',{name:'People & private chat'})).toBeVisible();
    await expect(contacts).toBeVisible();
    expect(await rail.evaluate(node=>getComputedStyle(node).position)).toBe(width>=1120?'sticky':'static');
    expect(await contacts.evaluate(node=>getComputedStyle(node).position)).toBe('static');
    await expect(page.getByRole('dialog',{name:'Your contacts'})).toHaveCount(0);
    await expect(page.getByRole('button',{name:'Contacts',exact:true})).toHaveCount(0);
    await expect(contacts.getByRole('link',{name:'Approved study partner'})).toBeVisible();
    await expect(contacts.getByText('Status not shared',{exact:true})).toBeVisible();
    expect(reads).toBeGreaterThan(0);
    await page.screenshot({path:info.outputPath('luqi-native-people-'+width+'.png'),fullPage:true});
    await contacts.getByRole('link',{name:'Approved study partner'}).click();
    await expect(page).toHaveURL(/#\/chat\/people\?circle=552987fe/);
    await expect(page.locator('.luqi-chat-shell')).toBeVisible();
    await expect(page.getByRole('heading',{name:'Private conversations'})).toBeVisible();
    await expect(rail.getByRole('heading',{name:'People & private chat'})).toBeVisible();
    await expect(page.getByRole('link',{name:'Sign in to Luqi'})).toHaveCount(0);
    expect(logins).toBe(1);expect(paid).toBe(0);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  });
}
test('guest mobile People is in Luqi and never reads account contacts',async({page})=>{
  let reads=0;await page.route('**/api/v1/p2p/**',r=>{reads++;return r.abort()});
  await page.setViewportSize({width:320,height:740});
  await page.goto('/#/');
  await expect(page.getByRole('region',{name:'Your contacts'})).toBeVisible();
  await expect(page.getByRole('link',{name:'Sign in to see contacts'})).toBeVisible();
  await expect(page.getByRole('dialog',{name:'Your contacts'})).toHaveCount(0);
  expect(reads).toBe(0);
  await page.goto('/#/chat/people');
  await expect(page.getByRole('navigation',{name:'Mobile chat navigation'})).toBeVisible();
  await expect(page.getByRole('link',{name:'People',exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'Private conversations'})).toBeVisible();
  expect(reads).toBe(0);
});
